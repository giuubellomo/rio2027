/** La palabra de una fecha 'YYYY-MM-DD': siempre la misma para todas ese día. */
export function palabraDelDia(iso) {
  const dia = Math.floor(Date.parse(iso + 'T00:00:00Z') / 86400000);
  const [palabra, significado] = PALABRAS[((dia % PALABRAS.length) + PALABRAS.length) % PALABRAS.length];
  return { palabra, significado };
}
